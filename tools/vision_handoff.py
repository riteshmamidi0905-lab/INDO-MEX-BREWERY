#!/usr/bin/env python3
"""Generate vision/production/CHATGPT-HANDOFF.md from VP-AUDIT.csv + the two text blocks (Sprint 26).
The handoff is generated so the CSV stays the single source of truth. Usage: python3 tools/vision_handoff.py [write|--check]"""
import csv, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "vision/production")
OUT = os.path.join(D, "CHATGPT-HANDOFF.md")

def render():
    lock = open(os.path.join(D, "GLOBAL-LOCK-BLOCK.txt"), encoding="utf-8").read().strip()
    neg = open(os.path.join(D, "GLOBAL-NEGATIVES.txt"), encoding="utf-8").read().strip()
    rows = list(csv.DictReader(open(os.path.join(D, "VP-AUDIT.csv"), encoding="utf-8")))
    o = ["<!-- GENERATED by tools/vision_handoff.py from vision/production/VP-AUDIT.csv. Do not edit by hand. -->",
         "# NASHA VISION: CHATGPT HANDOFF PACK", "",
         "*VISION layer. These requests make concept visualizations of a fictional future place. They are not photographs, not products and not evidence. No logo, no trademark symbol (D-66). Nothing here is to be published.*", "",
         "## How to use", "1. Do the rounds in order (1 to 5). Do not skip ahead.",
         "2. For each asset, copy the block under **PASTE THIS** into one ChatGPT message. Attach the images listed under **Attach**.",
         "3. Choose a landscape 3:2 size in the ChatGPT image size option (do not type the size into the prompt).",
         "4. Check the **Success criteria** and the **Must not change** list. If it fails, say exactly what is wrong and regenerate; if it fails twice, tell Claude and the lock block will be fixed instead.",
         "5. Save the accepted image and register it: `python3 tools/vision_check.py register VP-01 path/to/file.png --date YYYY-MM-DD --edit none`.", "",
         "Assets, in order: " + ", ".join(f"{r['id']} (round {r['generation_round']})" for r in rows), ""]
    for r in sorted(rows, key=lambda x: (x["generation_round"], x["id"])):
        o += [f"---", f"## {r['id']} · {r['title']}", f"**Round {r['generation_round']} · class: {r['asset_class']} · status: {r['status']}**", "",
              f"**What to generate.** {r['purpose']}.", "",
              f"**Website destination.** {r['website_location']}", "",
              f"**Aspect ratio.** {r['aspect_ratio']}", f"**Desktop crop.** {r['desktop_crop']}", f"**Mobile crop.** {r['mobile_crop']}", "",
              f"**Attach.** {r['continuity_refs']} ({r['dependencies']})", "",
              "**PASTE THIS**", "```text", lock, "", "THIS IMAGE: " + r["final_prompt"], "",
              "NEGATIVE REQUIREMENTS: " + neg + "; " + r["specific_negatives"] + ".", "```", "",
              f"**Must not change.** {r['what_must_not_change']}", "", f"**Success criteria.** {r['success_criteria']}", ""]
    return "\n".join(o) + "\n"

if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text: print("STALE: run python3 tools/vision_handoff.py"); sys.exit(1)
        print("fresh"); sys.exit(0)
    open(OUT, "w", encoding="utf-8").write(text); print("wrote", os.path.relpath(OUT, ROOT), len(text), "bytes")
