#!/usr/bin/env python3
"""Generate docs/tools/TOOL-MAP.md: every tool, its one-line purpose (first docstring line or comment), what references it, and a rough role. Flags tools nothing references.
  python3 tools/tool_map.py"""
import os, re, glob, subprocess
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(R)
files = sorted(glob.glob("tools/*.py") + glob.glob("tools/*.sh"))
text = {}
for f in glob.glob("**/*", recursive=True):
    if os.path.isfile(f) and f.endswith((".md", ".py", ".sh", ".csv", ".json")) and "node_modules" not in f and not f.startswith(".git/"):
        try: text[f] = open(f, encoding="utf-8", errors="ignore").read()
        except Exception: pass
def purpose(f):
    s = text[f]
    m = re.search(r'"""(.+?)(?:\n|""")', s, re.S)
    if m: return re.sub(r"\s+", " ", m.group(1)).strip()[:110]
    for l in s.splitlines():
        if l.startswith("#") and not l.startswith("#!"): return l.lstrip("# ").strip()[:110]
    return ""
def role(f):
    n = os.path.basename(f)
    if n.startswith("validate") or n in ("security_check.sh", "diet_audit.py"): return "VALIDATOR"
    if n in ("founder_center.py", "action_board.py", "control_center.py", "dashboard.py", "tool_map.py", "make_session_cards.py", "decision_register.py"): return "GENERATOR"
    if n in ("t1_record.py", "session_record.py", "photo_ingest.py", "intake.py", "experiment_stats.py", "lit_ledger.py"): return "RECORDER / INGEST"
    return "HELPER / MODEL"
rows = []
for f in files:
    n = os.path.basename(f)
    refs = [g for g, t in text.items() if g != f and n in t and not g.startswith("docs/tools/TOOL-MAP")]
    rows.append((n, role(f), purpose(f), len(refs)))
L = ["# Tool map (generated by tools/tool_map.py; do not hand-edit)", "", "One command validates everything: `bash tools/validate_all.sh`. One tool ingests real inputs: `python3 tools/intake.py` (`route` shows where each kind goes). 'Referenced by' counts other repository files that mention the tool; 0 means nothing points to it (check before ever removing: history is preserved).", "",
     "| Tool | Role | Purpose | Referenced by |", "|---|---|---|---|"]
for n, r, pu, c in rows: L.append(f"| `{n}` | {r} | {pu.replace('|', '/')} | {c}{' (UNREFERENCED)' if c == 0 else ''} |")
open("docs/tools/TOOL-MAP.md", "w", encoding="utf-8").write("\n".join(L) + "\n"); print(f"wrote docs/tools/TOOL-MAP.md ({len(rows)} tools)")
