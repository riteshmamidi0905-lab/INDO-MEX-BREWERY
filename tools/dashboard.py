#!/usr/bin/env python3
"""Generate docs/PROTOTYPE-READINESS.md from repository facts. Nothing is marked done unless a real result row exists."""
import csv, json, os, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def p(*a): return os.path.join(R, *a)
def rows(f):
    try: return list(csv.DictReader(open(p(f))))
    except FileNotFoundError: return []
def real(f):
    return [r for r in rows(f) if (r.get('data_source') or '').strip().lower() == 'real_cook']

sessions = json.load(open(p('food/sessions/sessions.json')))['sessions']
sess_real = real('food/sessions/results.csv')
t1_real = real('food/t1-results/t1-results.csv')
costing_ing = rows('food/costing/ingredients.csv')
food = {r['id']: r for r in rows('food/CORE5-FOOD-MATRIX.csv')}
beer = rows('beer/CORE5-BEER-MATRIX.csv')

def sess_id(fid):
    return {'chicken-65-totopos': 'Session 1', 'paneer-tikka-taco': 'Session 2', 'gobi-taco': 'Session 3',
            'butter-chicken-quesadilla': 'Session 4', 'goat-birria': 'Session 5'}[fid]

def nxt(fid):
    if fid == 'chicken-65-totopos': return 'Cook Session 1 exactly as frozen (sheet 13)'
    return f"Cook per food/sessions/{ {'paneer-tikka-taco':'S2-paneer-tikka-taco','gobi-taco':'S3-gobi-taco','butter-chicken-quesadilla':'S4-butter-chicken-quesadilla','goat-birria':'S5-goat-birria'}[fid] }.md (after Session 1)"

lines = ["# Prototype readiness (generated by tools/dashboard.py; do not hand-edit)",
 "", "Status words are read from repository files. A cell says DONE only if a real recorded result exists. Today none does, so most cells are NOT DONE or OPEN on purpose. This page does not change any readiness score (see docs/readiness/VALIDATION-SCOREBOARD.md). A frozen gate is only meaningful once D-76 and sessions.json are committed and the founder has approved the thresholds.", "",
 "See also: `docs/CORE5-CONTROL-CENTER.md` (one page per product), `docs/EXTERNAL-INPUT-QUEUE.md` (who to ask), `food/t1-test-sheets/14-SESSION-1-FOUNDER-MODE.md` (cook Session 1).", "",
 "## Foods", "",
 "| Food | Session | Research | Protocol | Ingredients | Equipment | Frozen gates | Cooked? | Iterations | Photo evidence | Decision | Next action |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for fid in ['chicken-65-totopos', 'paneer-tikka-taco', 'gobi-taco', 'butter-chicken-quesadilla', 'goat-birria']:
    s = sessions.get(fid)
    if fid == 'chicken-65-totopos':
        proto = 'Sheet 13 (frozen D-74)'; ing = 'Shopping list in sheet 13'; eq = 'Sheet 13'; gates = 'FROZEN (D-74)'
        cooked = 'YES' if t1_real else 'NOT PERFORMED'; it = len(t1_real); photos = 'none'
    else:
        proto = 'Card + sessions.json' if s else 'MISSING'
        ing = 'Procurement checklist (prices blank)' if s else 'MISSING'
        eq = 'Listed' if s and s.get('equipment_required') else 'MISSING'
        gates = 'FROZEN (D-76 hash)' if s else 'OPEN'
        mine = [r for r in sess_real if r.get('dish_id') == fid]
        cooked = 'YES' if mine else 'NOT PERFORMED'; it = len({r.get('iteration') for r in mine}); photos = 'none' if not mine else 'see results.csv'
    lines.append(f"| {food[fid]['name']} | {sess_id(fid)} | Web summaries only (T1) | {proto} | {ing} | {eq} | {gates} | {cooked} | {it} | {photos} | NO DECISION | {nxt(fid)} |")

lines += ["", "## Beers", "", "| Beer | Reference | Brief | Brewer reviewed? | Pilot pathway | Brewed? | Sensory tested? | Pairing tested? | Founder / recommended pilot order | Next action |", "|---|---|---|---|---|---|---|---|---|---|"]
for b in beer:
    brief = 'Written' if os.path.exists(p('beer/pilot-briefs')) and any(f.startswith(('0' + str(beer.index(b) + 1))) for f in os.listdir(p('beer/pilot-briefs'))) else 'MISSING'
    lines.append(f"| {b['name']} | {b['style_reference']} (style-typical, not a recipe) | {brief} | NO (AI review only; not a qualified brewer) | UNKNOWN (TTB/TABC/space not resolved) | {'NO' if b['physical_status']=='NOT BREWED' else '?'} | NO | NO | {b['pilot_order_founder']} / {b['pilot_order_recommended'].split(' ')[0]} | {b['next_physical_step']} |")

lines += ["", "## Costing and operations", "",
 f"- Ingredient rows: {len(costing_ing)}; priced rows: {sum(1 for r in costing_ing if (r.get('price_per_unit') or '').strip())} (0 means every recipe is NOT COSTABLE).",
 "- Kitchen capacity: planning exercise only (ops/kitchen); no ticket-time data.",
 "- Glass V2: concept geometry, manufacturability unverified.", "",
 "## Order of physical work", "",
 "1. Session 1 Chicken 65 Totopos (food/t1-test-sheets/13 shopping list and cook card), then 2. Session 2 paneer, 3. Session 3 gobi, 4. Session 4 quesadilla, 5. Session 5 goat (needs sourcing first). Beer: send the brewer handoff to a professional brewer; nothing is brewed by the repository.", ""]
out = "\n".join(lines)
if '--check' in sys.argv:
    cur = open(p('docs/PROTOTYPE-READINESS.md')).read() if os.path.exists(p('docs/PROTOTYPE-READINESS.md')) else ''
    sys.exit(0 if cur == out + "\n" else 1)
open(p('docs/PROTOTYPE-READINESS.md'), 'w').write(out + "\n")
print('wrote docs/PROTOTYPE-READINESS.md')
