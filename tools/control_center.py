#!/usr/bin/env python3
"""Generate docs/CORE5-CONTROL-CENTER.md: one place for the ten Core 5 products. Reads the canonical matrices, sessions.json and the pairing flight; invents nothing.
  python3 tools/control_center.py        write the file       python3 tools/control_center.py --check   exit 1 if the file is stale"""
import csv, json, os, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def p(*a): return os.path.join(R, *a)
def rows(f): return list(csv.DictReader(open(p(f), encoding="utf-8")))
foods, beers = rows("food/CORE5-FOOD-MATRIX.csv"), rows("beer/CORE5-BEER-MATRIX.csv")
flight = rows("food/CORE5-PAIRING-FLIGHT-1.csv")
sess = json.load(open(p("food/sessions/sessions.json"), encoding="utf-8"))["sessions"]
SESSION_NO = {"chicken-65-totopos": 1, "paneer-tikka-taco": 2, "gobi-taco": 3, "butter-chicken-quesadilla": 4, "goat-birria": 5}
CARD = {"paneer-tikka-taco": "S2-paneer-tikka-taco", "gobi-taco": "S3-gobi-taco", "butter-chicken-quesadilla": "S4-butter-chicken-quesadilla", "goat-birria": "S5-goat-birria"}
BREWER = {"hefeweizen": "01-hefeweizen", "mexican-lager": "02-mexican-style-lager", "vienna-amber": "03-vienna-amber", "pilsner": "04-pilsner", "witbier": "05-witbier"}
NAMES = {b["id"]: b["name"] for b in beers}; FNAMES = {f["id"]: f["name"] for f in foods}
def gates_text(fid):
    if fid == "chicken-65-totopos":
        return "D-74 (frozen): Chicken 65 identity, totopo identity, fusion coherence, another bite >= 4.0; T+10 crispness, structure >= 3.5; no failure code (NOT_65, NO_CORN, SOGGY, IMPRACTICAL, COLLAPSE, SAUCE_DOMINATES, GENERIC_NACHOS, UNRELATED_CHIPS, D54, UNSAFE); 2 passing iterations"
    g = sess[fid]["gates"]
    return "D-76 (AGENT-PROPOSED, founder confirmation required before Session 2): " + ", ".join(f"{k} >= {v['min']}" for k, v in g.items()) + "; failure gates; 2 passing iterations; NASHA R&D THRESHOLDS, not industry standards"
def pf(fid=None, bid=None):
    out = []
    for r in flight:
        if (fid and r["food_id"] == fid) or (bid and r["beer_id"] == bid):
            other = NAMES[r["beer_id"]] if fid else FNAMES[r["food_id"]]
            out.append(f"{r['pairing_id']} {other} ({r['tier']}; mechanisms {r['agent_mechanisms']}; risk: {r['predicted_risk']})")
    return "; ".join(out) or "none in the first flight"
ings = rows("food/costing/ingredients.csv")
priced = sum(1 for r in ings if (r.get("price_per_unit") or "").strip())
COSTLINE = f"{priced} of {len(ings)} ingredient rows have a price" + (", so no plate is costable." if priced == 0 else "; check price_class before using any cost.")
rules = {r["product_id"]: r for r in rows("docs/company/data/core5-decision-rules.csv")}
def rule(pid):
    r = rules[pid]
    return f"- **KILL / REVISE RULE (proposals; no result exists):** CONTINUE if {r['continue_if']}. REVISE if {r['revise_if']}. DE-PRIORITIZE if {r['de_prioritize_if']}. REMOVE if {r['remove_if']}. Guard: {r['sunk_cost_guard']}."
L = ["# Core 5 control center (generated by tools/control_center.py; do not hand-edit)", "",
     "One place for the ten products: what we know, what we assume, what must happen next, and what could kill each. Every line comes from the canonical matrices, `food/sessions/sessions.json`, the first pairing flight or the briefs. Nothing here is a result. Evidence 4/95, design 43/95, all five foods NOT PERFORMED, all five beers NOT BREWED, all pairings PROPOSED PAIRING - NOT SENSORY TESTED. Cost data: " + COSTLINE + "", "",
     "## Foods", ""]
for f in foods:
    fid = f["id"]; n = SESSION_NO[fid]
    plan = "food/t1-test-sheets/14-SESSION-1-FOUNDER-MODE.md" if n == 1 else f"food/sessions/{CARD[fid]}.md"
    L += [f"### {f['name']} (Session {n})",
          f"- **STATUS:** {f['physical_test_status']} (concept; concept-design confidence, not evidence: {f['confidence']})",
          f"- **HYPOTHESIS:** {f['nasha_transformation']}",
          f"- **CULTURAL BASIS:** Indian: {f['indian_anchor']} | Mexican: {f['mexican_anchor']} | class: {f['cultural_class']} (no advisor has reviewed it)",
          f"- **PRIMARY UNKNOWN:** {f['reference_gaps']}",
          f"- **PHYSICAL TEST REQUIRED:** {f['next_experiment']} (card: `{plan}`)",
          f"- **PROFESSIONAL REVIEW REQUIRED:** Indian and Mexican culinary advisors (`docs/CULTURAL-REVIEW-PACK.md`); chef for execution; food-safety professional for holding/cooling",
          f"- **COST DATA REQUIRED:** real purchase price, trim and cooked yield, portion, oil and garnish allocation (`food/costing/`); prices blank today",
          f"- **OPERATIONAL RISK:** holding {f['holding_risk']}; execution {f['execution_risk']}; equipment: {f['equipment']}",
          f"- **PAIRING HYPOTHESIS:** {pf(fid=fid)}",
          f"- **PASS/FAIL GATE:** {gates_text(fid)}",
          rule(fid),
          f"- **EVIDENCE STATUS:** none (planning only)",
          f"- **NEXT ACTION:** " + ("Founder cooks Session 1 per the founder-mode card" if n == 1 else "wait for Session 1; confirm the D-76 thresholds first"), ""]
L += ["## Beers", ""]
for b in beers:
    bid = b["id"]
    L += [f"### {b['name']}",
          f"- **STATUS:** {b['physical_status']} (brief written; no recipe exists)",
          f"- **HYPOTHESIS:** {b['style_role']}; pairing role: {b['food_pairing_role']}",
          f"- **CULTURAL BASIS:** style reference {b['style_reference']} (style-typical, not a NASHA recipe); no cultural claim beyond the style",
          f"- **PRIMARY UNKNOWN:** {b['brewer_questions']}",
          f"- **PHYSICAL TEST REQUIRED:** {b['next_physical_step']} (brief: `beer/pilot-briefs/{BREWER[bid]}.md`)",
          f"- **PROFESSIONAL REVIEW REQUIRED:** qualified head brewer (`beer/pilot-briefs/00-BREWER-HANDOFF.md`, `beer/pilot-briefs/BREWER-REVIEW-FORM.md`); alcohol attorney for any pilot pathway",
          f"- **COST DATA REQUIRED:** pilot-batch quote, ingredient quotes, labour, excise (none received); regulatory/ingredient issues: {b['regulatory_ingredient_issues']}",
          f"- **OPERATIONAL RISK:** tank time and lager/ale scheduling; glass: {b['glass_role']} (Glass V2 is a concept; manufacturability unverified)",
          f"- **PAIRING HYPOTHESIS:** {pf(bid=bid)}",
          f"- **PASS/FAIL GATE:** none frozen yet; pilot gates are proposed in the brewer handoff and need a brewer's view; pilot order founder {b['pilot_order_founder']} / recommended {b['pilot_order_recommended'].split(' ')[0]}",
          rule(bid),
          f"- **EVIDENCE STATUS:** none (planning only)",
          f"- **NEXT ACTION:** a qualified brewer reads the handoff and answers the review form", ""]
out = "\n".join(L)
path = p("docs/CORE5-CONTROL-CENTER.md")
if "--check" in sys.argv: sys.exit(0 if os.path.exists(path) and open(path, encoding="utf-8").read() == out + "\n" else 1)
open(path, "w", encoding="utf-8").write(out + "\n"); print("wrote docs/CORE5-CONTROL-CENTER.md")
