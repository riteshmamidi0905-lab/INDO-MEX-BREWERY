#!/usr/bin/env python3
"""Core 5 kitchen CAPACITY PLANNING EXERCISE (Sprint 17). Not a forecast. Reads ops/kitchen/capacity-assumptions.json (every number an ASSUMPTION with a low/base/high range),
computes for N simultaneous orders the lower-bound minutes each station needs (demand / slots) and which station is the bottleneck, then samples the ranges (Monte Carlo, seeded)
to show how stable that conclusion is. It ignores arrival patterns, ticket coordination, walking, holding and mistakes, so real clear-times are LONGER. The output is a list of what real
ticket-time data to measure first.
  python3 tools/kitchen_capacity.py            print the exercise (markdown)
  python3 tools/kitchen_capacity.py selftest"""
import json, sys
import numpy as np
P = "ops/kitchen/capacity-assumptions.json"
def load(p=P): return json.load(open(p, encoding="utf-8"))
def tri(r, rng): return rng.triangular(r[0], r[1], r[2]) if r[2] > r[0] else r[1]
def clear_times(A, mix, N, draw):
    tot = sum(mix.values()); plates = {d: N * w / tot for d, w in mix.items()}
    out = {}
    for st in A["stations"]:
        demand = sum(plates[d] * draw(A["dishes"][d][st]) for d in plates)
        out[st] = demand / max(draw(A["stations"][st]["slots"]), 1e-9)
    return out
def run(A, trials=4000, seed=7):
    rng = np.random.default_rng(seed); res = []
    for mname, mix in A["mixes"].items():
        for N in A["scenarios_simultaneous_orders"]:
            base = clear_times(A, mix, N, lambda r: r[1]); bott = max(base, key=base.get)
            cnt = {s: 0 for s in A["stations"]}; spans = []
            for _ in range(trials):
                ct = clear_times(A, mix, N, lambda r: tri(r, rng)); b = max(ct, key=ct.get); cnt[b] += 1; spans.append(ct[b])
            res.append(dict(mix=mname, N=N, base_bottleneck=bott, base_minutes=round(base[bott], 1), base_all={k: round(v, 1) for k, v in base.items()}, share={k: round(v / trials * 100) for k, v in cnt.items() if v}, p10=round(float(np.percentile(spans, 10)), 1), p50=round(float(np.percentile(spans, 50)), 1), p90=round(float(np.percentile(spans, 90)), 1)))
    return res
def report(A):
    L = ["# Core 5 kitchen capacity exercise (generated by tools/kitchen_capacity.py)", "", A["status"], "", "| Mix | Orders at once | Base-case bottleneck (min to clear, lower bound) | Share of sampled ranges where each station is the bottleneck | Bottleneck clear time p10 / p50 / p90 (min) | Upper-bound orders per 15 min at the base-case bottleneck |", "|---|---|---|---|---|---|"]
    for r in run(A): L.append(f"| {r['mix']} | {r['N']} | {r['base_bottleneck']} ({r['base_minutes']}) | {r['share']} | {r['p10']} / {r['p50']} / {r['p90']} | {round(r['N'] * 15 / r['base_minutes'], 1) if r['base_minutes'] else 'n/a'} |")
    return "\n".join(L)
def selftest():
    A = {"stations": {"a": {"slots": [1, 1, 1]}, "b": {"slots": [10, 10, 10]}}, "dishes": {"d": {"a": [2, 2, 2], "b": [1, 1, 1]}}, "mixes": {"m": {"d": 1}}, "scenarios_simultaneous_orders": [10]}
    r = run(A, trials=50)[0]; assert r["base_bottleneck"] == "a" and r["base_minutes"] == 20.0 and r["share"] == {"a": 100}
    print("selftest ok: bottleneck = demand / slots, stable across sampled ranges")
if __name__ == "__main__":
    if sys.argv[1:] == ["selftest"]: selftest()
    else: print(report(load()))
