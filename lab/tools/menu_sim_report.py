#!/usr/bin/env python3
"""Full-menu simulation report (D-90): builds the SYNTHETIC current-menu scenario and the historical one side by side and writes lab/results/menu_sim_d90.json and docs/engineering/D-90-MENU-SIMULATION.md.
All numbers are read from the built warehouses. Planning assumptions and synthetic sales; nothing is a business result.   cd lab && python3 tools/menu_sim_report.py"""
import json
import sqlite3
import subprocess
import sys
import tempfile
from pathlib import Path

LAB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(LAB))
from nasha_lab import enterprise_sim as es  # noqa: E402
from nasha_lab.recipes import menu  # noqa: E402
from nasha_lab.warehouse import pipeline, scenario  # noqa: E402

BASE = dict(months=10, fast_casual=3, beer_gardens=1, target_orders=30_000, loyalty_profiles=2_500, employees=60, open_at_start=3)


def build(kind):
    d = Path(tempfile.mkdtemp(prefix=f"menu-{kind}-"))
    es.generate(es.SimConfig(name=kind, **({"menu": "current"} if kind == "current" else {}), **BASE), d / "src"); pipeline.run(d / "src", d / "w.db"); scenario.build(d / "w.db")
    c = sqlite3.connect(d / "w.db")
    prof = c.execute("""SELECT p.menu_item_id, m.name, m.menu_status, sum(p.units), sum(p.restated_net_cents), sum(p.food_and_consumables_cents), sum(p.gross_profit_cents), e.menu_class
                        FROM scn_menu_profitability_month p JOIN scn_menu_item m USING(menu_item_id) JOIN scn_menu_engineering e USING(menu_item_id) GROUP BY 1 ORDER BY 7 DESC""").fetchall()
    out = dict(dishes=[dict(dish=r[0], name=r[1], recipe_status=r[2], units=r[3], restated_net_usd=round(r[4] / 100), food_cost_usd=round(r[5] / 100), gross_profit_usd=round(r[6] / 100), gp_pct=round(100 * r[6] / r[4], 1), menu_class=r[7]) for r in prof],
               flags=c.execute("SELECT count(*) FROM scn_variance_flag").fetchone()[0], recos=c.execute("SELECT count(*) FROM scn_procurement_reco").fetchone()[0], forecast_rows=c.execute("SELECT count(*) FROM scn_demand_forecast").fetchone()[0],
               ingredients=c.execute("SELECT count(DISTINCT ingredient_id) FROM scn_depletion_week").fetchone()[0], orders=c.execute("SELECT count(*) FROM fact_order").fetchone()[0], score=scenario.score_detection(c))
    c.close()
    return out


def main():
    cur, his = build("current"), build("historical")
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=LAB).stdout.strip()
    rep = dict(schema="menu-sim-d90/1", commit=commit, synthetic=True, current_menu=menu.load("current")["menu_id"], historical_menu=menu.load("historical")["menu_id"], current=cur, historical=his, profile=BASE)
    (LAB / "results").mkdir(exist_ok=True); (LAB / "results/menu_sim_d90.json").write_text(json.dumps(rep, indent=1))
    md = ["# D-90 full-menu simulation (SYNTHETIC)", "", f"Generated by `lab/tools/menu_sim_report.py` at `{commit}`. Current menu: `{rep['current_menu']}`; historical scenario: `{rep['historical_menu']}` (preserved, reproducible).",
          "Founder decision D-90: Tandoori Lamb Tacos is the approved replacement candidate for the retired Goat Birria, at $18.50. **Its recipe and costing stay provisional; it has not been cooked or tested.** Goat Birria is absent from this simulation; its raw rows in the historical data set are untouched.", "",
          "## Current menu (6 dishes, all simulated end to end)", "", "| Dish | Recipe status | Units | Net revenue $ | Food+consumables $ | Gross profit $ | GP % | Class |", "|---|---|---|---|---|---|---|---|"]
    md += [f"| {d['name']} | {d['recipe_status']} | {d['units']:,} | {d['restated_net_usd']:,} | {d['food_cost_usd']:,} | {d['gross_profit_usd']:,} | {d['gp_pct']} | {d['menu_class']} |" for d in cur["dishes"]]
    md += ["", f"Orders {cur['orders']:,}; {cur['ingredients']} ingredients with depletion; {cur['forecast_rows']:,} forecast rows; {cur['flags']} variance flags; {cur['recos']} procurement recommendations (all PROPOSED; a purchase order draft needs the THE WEIR human approval path, tested for lamb in `lab/tests/test_menu_d90.py`).",
           f"Variance detection on this scenario's injected anomalies: {cur['score']}.", "", "## Historical scenario (4 mapped dishes + unmapped Goat Birria slot M03)", "", "| Dish | Units | Net revenue $ | GP % | Class |", "|---|---|---|---|---|"]
    md += [f"| {d['name']} | {d['units']:,} | {d['restated_net_usd']:,} | {d['gp_pct']} | {d['menu_class']} |" for d in his["dishes"]]
    md += ["", "Revenue and units differ between the two scenarios because they are different synthetic data sets (different catalogue, so different random draws), not because history was rewritten.", "",
           "Caveats: synthetic sales; popularity weights are simulation parameters; costs are planning assumptions at PLANNING base prices, not supplier quotes; the lamb margin is the D-88 69.4% planning figure and carries high price risk."]
    (LAB.parent / "docs/engineering/D-90-MENU-SIMULATION.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
