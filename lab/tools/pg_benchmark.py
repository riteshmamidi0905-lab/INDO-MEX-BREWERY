#!/usr/bin/env python3
"""Reproducible PostgreSQL migration + query-plan benchmark on the dev-profile SYNTHETIC warehouse (embedded PostgreSQL, or NASHA_PG_DSN).
Writes lab/results/pg_benchmark.json and docs/engineering/D-89-POSTGRES-HARDENING.md. Local measurement only: one machine, small tables, no concurrency; it is not a performance claim about any deployment.
    cd lab && python3 tools/pg_benchmark.py"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

LAB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(LAB))
from nasha_lab import enterprise_sim as es  # noqa: E402
from nasha_lab.warehouse import pg_hardening as H, pg_variant as V, pipeline, scenario  # noqa: E402
import psycopg  # noqa: E402


def main():
    d = Path(tempfile.mkdtemp(prefix="pgbench-"))
    es.generate(es.PROFILES["dev"], d / "src"); pipeline.run(d / "src", d / "w.db"); scenario.build(d / "w.db")
    srv = None
    dsn = os.environ.get("NASHA_PG_DSN")
    if not dsn:
        import pixeltable_pgserver as pg
        srv = pg.get_server(str(d / "pgdata"), cleanup_mode="stop"); dsn = srv.get_uri()
    V.build_pg(d / "w.db", dsn); V.build_scn(d / "w.db", dsn)
    with psycopg.connect(dsn, autocommit=True) as c:
        c.execute('SET search_path TO "nasha_wh", pg_catalog, public'); c.execute("ANALYZE")
        rows = {t: c.execute(f"SELECT count(*) FROM {t}").fetchone()[0] for t in ("scn_depletion_day", "scn_procurement_reco", "scn_supplier_quote", "scn_demand_forecast")}
        server = c.execute("SHOW server_version").fetchone()[0]
    H.migrate(dsn, H.SCHEMA, specs={v: H.statements(v) for v in ("001", "002", "003")})
    with psycopg.connect(dsn, autocommit=True) as c:
        c.execute('SET search_path TO "nasha_wh", pg_catalog, public'); c.execute("ANALYZE")
    before = H.benchmark(dsn, repeats=30)
    rep = H.migrate(dsn)
    with psycopg.connect(dsn, autocommit=True) as c:
        c.execute('SET search_path TO "nasha_wh", pg_catalog, public'); c.execute("ANALYZE")
    after = H.benchmark(dsn, repeats=30)
    desc = H.describe(dsn)
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=LAB).stdout.strip()
    desc["constraints"] = [c for c in desc["constraints"] if c["table"].startswith("scn_")]     # the scenario tables this migration set governs
    out = dict(schema="pg-benchmark/1", commit=commit, postgres=server, profile="dev", synthetic=True, rows=rows, migration_final_step=rep, constraints=len(desc["constraints"]), indexes=len(desc["indexes"]),
               before_index_migration=before, after_index_migration=after, note="Local measurement; embedded PostgreSQL; synthetic data; medians of 30 runs after one warm-up. Not a performance claim about any deployment.")
    (LAB / "results").mkdir(exist_ok=True)
    (LAB / "results/pg_benchmark.json").write_text(json.dumps(out, indent=1))
    md = ["# PostgreSQL hardening evidence (D-89)", "", f"Generated by `lab/tools/pg_benchmark.py` at commit `{commit}`; PostgreSQL {server}; dev-profile SYNTHETIC warehouse. **Local measurement on one machine; not a performance claim about any deployment.**", "",
          f"Constraints now enforced by the database on the scenario (scn_) tables: {sum(c['type'] == 'PRIMARY KEY' for c in desc['constraints'])} primary keys, {sum(c['type'] == 'FOREIGN KEY' for c in desc['constraints'])} foreign keys, {sum(c['type'] == 'CHECK' for c in desc['constraints'])} CHECK constraints (tests prove violations are rejected, `lab/tests/test_pg_hardening.py`).", "",
          "Migration safety: pre-flight counts violating rows and blocks before changing anything; each migration is one transaction (a failing statement rolls everything back); foreign keys are added NOT VALID then VALIDATEd; applied migrations are checksummed so a re-run is a no-op and an edited migration is detected.", "",
          "| Query | Rows | Before index (median ms) | Plan before | After index (median ms) | Plan after |", "|---|---|---|---|---|---|"]
    for q in before:
        b, a = before[q], after[q]
        md.append(f"| {q} | {a['rows']} | {b['median_ms']} | {' > '.join(b['plan']['nodes'][:3])} | {a['median_ms']} | {' > '.join(a['plan']['nodes'][:3])} |")
    md += ["", f"Table sizes: {rows}.", "", "Reading the table: the tables are small (hundreds to a few thousand rows), so timings are sub-millisecond either way and the differences are within noise; the evidence is the PLAN change (a sequential scan became an index scan for the recommendation lookup) and that the constraints reject bad data. No speed-up is claimed. Quotes for one ingredient stays a sequential scan because the table has 210 rows."]
    Path(LAB.parent / "docs/engineering/D-89-POSTGRES-HARDENING.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    if srv:
        srv.cleanup()


if __name__ == "__main__":
    main()
