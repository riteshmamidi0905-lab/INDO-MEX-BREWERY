#!/usr/bin/env python3
"""Growth OS capability tracker: validates lab/nasha_lab/growth/capabilities.json against the repository and writes docs/growth-os/CAPABILITY-STATUS.md.
A status is only accepted if its evidence exists: TESTED/INTEGRATED need existing test functions, IMPLEMENTED/TESTED/INTEGRATED need existing code. All 25 capabilities must be present. No percentages are computed.
    cd lab && python3 tools/build_growth_capabilities.py"""
import json
import re
import sys
from pathlib import Path

LAB = Path(__file__).resolve().parents[1]
REPO = LAB.parent
SRC = LAB / "nasha_lab/growth/capabilities.json"


def problems(doc):
    bad = []
    caps = doc["capabilities"]
    if [c["n"] for c in caps] != list(range(1, 26)):
        bad.append("capabilities must be exactly 1..25 in order")
    for c in caps:
        st = c["status"]
        if st not in doc["statuses"]:
            bad.append(f"#{c['n']}: unknown status {st}")
        for p in c["code"]:
            if not (REPO / p).exists():
                bad.append(f"#{c['n']}: code path missing {p}")
        for t in c["tests"]:
            path, _, fn = t.partition("::")
            f = REPO / path
            if not f.exists() or not re.search(rf"def {re.escape(fn)}\b", f.read_text()):
                bad.append(f"#{c['n']}: test missing {t}")
        if st in ("TESTED", "INTEGRATED") and not c["tests"]:
            bad.append(f"#{c['n']}: {st} without a test")
        if st in ("IMPLEMENTED", "TESTED", "INTEGRATED") and not c["code"]:
            bad.append(f"#{c['n']}: {st} without code")
        if st == "INTEGRATED":
            bad.append(f"#{c['n']}: INTEGRATED needs a working UI, enforced authorization and audit end to end; none exists yet")
        if st != "NOT STARTED" and not c["done"]:
            bad.append(f"#{c['n']}: {st} must say what exists")
        if not c["missing"] and st != "INTEGRATED" and st != "NOT STARTED":
            bad.append(f"#{c['n']}: limitations must be documented")
    return bad


def main():
    doc = json.loads(SRC.read_text())
    bad = problems(doc)
    if bad:
        print("\n".join(bad)); sys.exit(1)
    counts = {s: sum(c["status"] == s for c in doc["capabilities"]) for s in doc["statuses"]}
    md = ["# NASHA Growth OS: capability status (25 capabilities)", "", "Generated by `lab/tools/build_growth_capabilities.py`; every code path and test cited is checked to exist. No completion percentage is computed: a capability counts only at the status its evidence supports.", "",
          "| Status | Count |", "|---|---|", *[f"| {k} | {v} |" for k, v in counts.items()], "", "| # | Capability | Status | What exists | What is missing |", "|---|---|---|---|---|"]
    for c in doc["capabilities"]:
        md.append(f"| {c['n']} | {c['capability']} | **{c['status']}** | {c['done'] or '—'} | {c['missing'] or '—'} |")
    md += ["", "Status rules: " + "; ".join(f"**{k}** — {v}" for k, v in doc["rules"].items()) + ". `BLOCKED` means an external dependency prevents progress (none currently).", "", "All data is synthetic. NASHA is a proposed business; no customer, transaction, campaign or financial outcome is real."]
    (REPO / "docs/growth-os").mkdir(exist_ok=True)
    (REPO / "docs/growth-os/CAPABILITY-STATUS.md").write_text("\n".join(md) + "\n")
    print(counts)


if __name__ == "__main__":
    main()
