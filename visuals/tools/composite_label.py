#!/usr/bin/env python3
"""Composite verified vector label art onto a BLANK cylindrical product plate (can/bottle). Works on a real photograph or a procedural plate.

  plate  : RGB image of a blank, unlabelled can (no text anywhere in the label zone)
  wrap   : flat label art (PNG rendered from the vector master), full circumference left->right
  region : (x0, y0, x1, y1) pixel box of the label zone on the plate, x0..x1 = can's visible width (diameter)

Method: cylindrical mapping (visible screen column u in [-1,1] -> angle asin(u) -> wrap column), the plate's own luminance inside the region
becomes the shading map (so real highlights/falloff of a photograph are kept), plus a printed-ink factor so white ink is never brighter than the
plate's highlight. Text is never generated by a model: it comes only from `wrap`.
"""
import math
import numpy as np
from PIL import Image


def cylinder_warp(wrap: Image.Image, width: int, height: int, center_frac: float = 0.5, rotate_deg: float = 0.0) -> Image.Image:
    """Return RGB of size (width,height): the front of the wrap as seen on a cylinder `width` px wide."""
    w = np.asarray(wrap.convert("RGB"), dtype=np.float32)
    W, H = wrap.size
    u = (np.arange(width) + .5) / width * 2 - 1                      # -1..1 across the visible diameter
    ang = np.arcsin(np.clip(u, -1, 1)) + math.radians(rotate_deg)    # visible half-circumference
    xs = (center_frac + ang / (2 * math.pi)) % 1.0 * W
    ys = (np.arange(height) + .5) / height * H
    x0 = np.floor(xs).astype(int) % W; x1 = (x0 + 1) % W; fx = (xs - np.floor(xs))[None, :, None]
    y0 = np.clip(np.floor(ys).astype(int), 0, H - 2); fy = (ys - y0)[:, None, None]
    a = w[y0][:, x0] * (1 - fx) + w[y0][:, x1] * fx
    b = w[y0 + 1][:, x0] * (1 - fx) + w[y0 + 1][:, x1] * fx
    out = a * (1 - fy) + b * fy
    # foreshortening: darken/compress toward the silhouette edge is done by shading; here only keep colour
    return Image.fromarray(np.clip(out, 0, 255).astype(np.uint8))


def composite(plate: Image.Image, wrap: Image.Image, region, center_frac=0.5, shade_strength=1.0, ink=0.96) -> Image.Image:
    x0, y0, x1, y1 = region
    p = np.asarray(plate.convert("RGB"), dtype=np.float32)
    zone = p[y0:y1, x0:x1]
    lum = zone.mean(axis=2, keepdims=True)
    ref = np.percentile(lum, 92)                                      # plate highlight level = "full ink"
    shade = np.clip(lum / max(ref, 1), 0, 1.15) ** shade_strength
    lab = np.asarray(cylinder_warp(wrap, x1 - x0, y1 - y0, center_frac), dtype=np.float32)
    # keep the plate's specular highlights (above ref) on top of the ink
    spec = np.clip(lum - ref, 0, None) * 1.2
    out = lab * shade * ink + spec
    res = p.copy(); res[y0:y1, x0:x1] = np.clip(out, 0, 255)
    return Image.fromarray(res.astype(np.uint8))


def blank_can_plate(w=520, h=980, bg=(222, 214, 200)) -> tuple:
    """PROCEDURAL blank aluminium can on a studio sweep (NOT a photograph). Returns (image, label_region)."""
    img = np.zeros((h, w, 3), np.float32)
    yy = np.linspace(0, 1, h)[:, None]
    sweep = np.array(bg, np.float32)[None, None, :] * (1.02 - .22 * yy)[..., None]
    img[:] = sweep
    cx, cw = w // 2, 300
    xL, xR = cx - cw // 2, cx + cw // 2
    top, bot = 110, 880
    u = (np.arange(xL, xR) + .5 - cx) / (cw / 2)
    ang = np.arcsin(np.clip(u, -1, 1))
    diff = np.cos(ang * .95)
    spec = np.exp(-((u + .38) / .09) ** 2) * .75 + np.exp(-((u - .62) / .05) ** 2) * .25
    base = 150 * diff * .8 + 70 + 120 * spec
    body = np.repeat(base[None, :], bot - top, axis=0)
    img[top:bot, xL:xR] = np.stack([body * 1.0, body * 1.0, body * 1.02], axis=2)
    # shoulders and rims (simple trapezoid taper + rim)
    for i in range(46):
        t = i / 45
        inset = int((1 - math.sin(t * math.pi / 2)) * 30)
        row = 64 + i
        seg = np.arange(xL + inset, xR - inset)
        uu = (seg + .5 - cx) / (cw / 2)
        v = (150 * np.cos(np.arcsin(np.clip(uu, -1, 1)) * .95) * .8 + 70 + 120 * np.exp(-((uu + .38) / .09) ** 2) * .75) * (.92 - .1 * (1 - t))
        img[row, xL + inset:xR - inset] = np.stack([v, v, v * 1.02], axis=1)
    img[110 - 0:112, xL:xR] *= .8
    # ground shadow
    for y in range(880, 925):
        a = (1 - (y - 880) / 45) * .35
        xs = np.arange(xL - 10, xR + 10)
        f = np.clip(1 - np.abs((xs - cx) / (cw / 2 + 25)) ** 2, 0, 1)
        img[y, xL - 10:xR + 10] *= (1 - a * f)[:, None]
    return Image.fromarray(np.clip(img, 0, 255).astype(np.uint8)), (xL, 135, xR, 850)
